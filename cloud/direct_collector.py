"""Direct retailer collection on a user-owned computer; encrypted results join the existing scan.

No remote commands are executed. Requests select only a run ID; retailer code is installed locally.
"""
from __future__ import annotations

import argparse
import dataclasses
import getpass
import json
import math
import os
from pathlib import Path
import re
import subprocess
import tempfile
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from urllib.parse import urlsplit

from matching.sizes import SizeInfo
from retailers.base import ParsedListing, RetailerAdapter, RetailerResult

REPOSITORY = "run-marko/patike"
RELEASE = "stanje"
HOSTS = {"djaksport": "www.djaksport.com", "planetasport": "planetasport.rs"}
HEARTBEAT = "direct-collector-heartbeat.json"
VERSION = 1
ROOT = Path(__file__).resolve().parent.parent
MAX_AGE = 4 * 3600
WAIT_SECONDS = 90 * 60


def now() -> float:
    return time.time()


def run_id(value: str) -> str:
    if not re.fullmatch(r"[1-9][0-9]{0,19}", str(value)):
        raise ValueError("Invalid scan run ID")
    return str(value)


def asset_name(kind: str, identity: str) -> str:
    return f"direct-{kind}-{run_id(identity)}." + ("enc" if kind == "response" else "json")


def gh(*args: str) -> str:
    try:
        result = subprocess.run(["gh", *args], capture_output=True, text=True, encoding="utf-8", timeout=120)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise RuntimeError("GitHub CLI nije dostupan ili je veza istekla.") from exc
    if result.returncode:
        raise RuntimeError("GitHub nije dostupan ili ključ nema potrebne dozvole.")
    return result.stdout


def upload(path: Path) -> None:
    gh("release", "upload", RELEASE, str(path), "--repo", REPOSITORY, "--clobber")


def download(name: str, directory: Path) -> Path:
    # Only names generated by this module are ever accepted by its callers.
    gh("release", "download", RELEASE, "--repo", REPOSITORY, "--pattern", name, "--dir", str(directory), "--clobber")
    return directory / name


def assets() -> dict[str, dict]:
    data = json.loads(gh("release", "view", RELEASE, "--repo", REPOSITORY, "--json", "assets"))
    return {item["name"]: item for item in data.get("assets", [])}


def crypt(mode: str, source: Path, target: Path) -> None:
    proc = subprocess.run(["node", str(ROOT / "cloud" / "crypt.mjs"), mode, str(source), str(target)],
                          capture_output=True, text=True, timeout=60)
    if proc.returncode:
        raise RuntimeError("Neuspešno šifrovanje ili dešifrovanje rezultata; proveri lozinku dashboarda.")


def fresh_timestamp(value, *, age=MAX_AGE, clock=None) -> float:
    clock = now() if clock is None else clock
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
        raise ValueError("Invalid timestamp")
    if not clock - age <= value <= clock + 60:
        raise ValueError("Expired result or incorrect computer clock")
    return float(value)


def validate_request(data: dict, identity: str | None = None) -> str:
    if data.get("version") != VERSION or data.get("repository") != REPOSITORY:
        raise ValueError("Unknown collector request")
    identity = run_id(identity or data.get("run_id", ""))
    if data.get("run_id") != identity:
        raise ValueError("Request belongs to another scan")
    fresh_timestamp(data.get("created_at"))
    return identity


def request() -> None:
    """Called once before the cloud scan. Offline collectors never delay other retailers."""
    identity = run_id(os.environ["GITHUB_RUN_ID"])
    try:
        with tempfile.TemporaryDirectory() as folder:
            folder = Path(folder)
            heartbeat = json.loads(download(HEARTBEAT, folder).read_text(encoding="utf-8"))
            if heartbeat.get("version") != VERSION or heartbeat.get("repository") != REPOSITORY:
                raise ValueError("Unknown collector")
            fresh_timestamp(heartbeat.get("updated_at"), age=180)
            payload = {"version": VERSION, "repository": REPOSITORY, "run_id": identity, "created_at": now()}
            path = folder / asset_name("request", identity)
            path.write_text(json.dumps(payload), encoding="utf-8")
            upload(path)
        with open(os.environ["GITHUB_ENV"], "a", encoding="utf-8") as output:
            output.write(f"DIRECT_COLLECTOR_RUN_ID={identity}\n")
        print("Đak i Planeta: zatraženo direktno očitavanje od lokalnog sakupljača.", flush=True)
    except (RuntimeError, ValueError, OSError, KeyError):
        print("::warning::Lokalni sakupljač nije povezan. Direktno očitavanje Đaka i Planete nije potvrđeno.", flush=True)


def finite_price(value):
    if value is not None and (isinstance(value, bool) or not isinstance(value, (int, float))
                              or not math.isfinite(value) or value <= 0):
        raise ValueError("Invalid price")
    return value


def validate_url(value: str, key: str) -> None:
    if not isinstance(value, str):
        raise ValueError("Invalid retailer URL")
    parsed = urlsplit(value)
    if (parsed.scheme != "https" or parsed.hostname != HOSTS[key] or parsed.username or parsed.password
            or parsed.port not in (None, 443)):
        raise ValueError("Result is not from the direct retailer")


def decode_results(payload: dict, identity: str) -> dict[str, RetailerResult]:
    if not isinstance(payload, dict) or payload.get("version") != VERSION or payload.get("repository") != REPOSITORY:
        raise ValueError("Unknown collector response")
    if payload.get("run_id") != run_id(identity):
        raise ValueError("Response belongs to another scan")
    fresh_timestamp(payload.get("created_at"))
    results = {}
    for key in HOSTS:
        if not isinstance(payload.get("results"), dict):
            raise ValueError("Invalid results")
        raw = payload["results"].get(key)
        if not isinstance(raw, dict) or raw.get("retailer") != key:
            raise ValueError("Missing retailer result")
        if raw.get("status") not in {"VERIFIED", "PARTIAL", "NOT_VERIFIED"}:
            raise ValueError("Unknown scan status")
        result = RetailerResult(key, raw["status"], str(raw.get("message") or "")[:1000] or None)
        for field in ("pages_ok", "pages_failed", "candidates"):
            value = raw.get(field, 0)
            if isinstance(value, bool) or not isinstance(value, int) or value < 0:
                raise ValueError("Invalid scan counters")
            setattr(result, field, value)
        listings = raw.get("listings", [])
        if not isinstance(listings, list) or len(listings) > 30000:
            raise ValueError("Invalid listing count")
        for item in listings:
            if not isinstance(item, dict):
                raise ValueError("Invalid listing object")
            if item.get("retailer") != key or item.get("seller"):
                raise ValueError("Marketplace data is not accepted")
            validate_url(item["url"], key)
            if not item.get("title") or item.get("availability") not in {"AVAILABLE", "OUT_OF_STOCK", "UNKNOWN"}:
                raise ValueError("Invalid listing")
            for name in ("current_price", "old_price", "regular_price", "loyalty_price", "coupon_price", "retailer_30d_min"):
                finite_price(item.get(name))
            sizes = []
            raw_sizes = item.get("sizes", [])
            if not isinstance(raw_sizes, list) or len(raw_sizes) > 200:
                raise ValueError("Invalid sizes")
            for size in raw_sizes:
                if not isinstance(size, dict):
                    raise ValueError("Invalid size object")
                if size.get("available") is not None and type(size["available"]) is not bool:
                    raise ValueError("Invalid size availability")
                if size.get("url"):
                    validate_url(size["url"], key)
                finite_price(size.get("price"))
                sizes.append(SizeInfo(**size))
            values = dict(item)
            values["sizes"] = sizes
            result.listings.append(ParsedListing(**values))
        if result.listings and (result.status == "NOT_VERIFIED" or not result.pages_ok):
            raise ValueError("Unverified source cannot supply listings")
        results[key] = result
    return results


class ResponseSource:
    """Both retailer threads share one authenticated snapshot and one download loop."""
    def __init__(self, identity: str, wait_seconds=WAIT_SECONDS):
        self.identity = run_id(identity)
        self.wait_seconds = wait_seconds
        self.lock = threading.Lock()
        self.results = None

    def load(self):
        with self.lock:
            if self.results is None:
                try:
                    deadline = time.monotonic() + self.wait_seconds
                    name = asset_name("response", self.identity)
                    with tempfile.TemporaryDirectory() as folder:
                        folder = Path(folder)
                        while True:
                            if name in assets():
                                encrypted = download(name, folder)
                                plain = folder / "response.json"
                                crypt("dec", encrypted, plain)
                                self.results = decode_results(json.loads(plain.read_text(encoding="utf-8")), self.identity)
                                print("Preuzeti direktni rezultati Đaka i Planete.", flush=True)
                                break
                            if time.monotonic() >= deadline:
                                raise RuntimeError("Lokalni sakupljač nije dostavio rezultate u predviđenom vremenu.")
                            time.sleep(20)
                except (RuntimeError, ValueError, OSError, KeyError, TypeError) as exc:
                    self.results = {key: RetailerResult(key, message=f"Direktni sakupljač: {exc}") for key in HOSTS}
            return self.results


class CollectedAdapter(RetailerAdapter):
    def __init__(self, original, source):
        self.original = original
        self.client = original.client
        self.source = source
        self.key, self.name, self.base_url = original.key, original.name, original.base_url

    def run(self, keep, max_pages=None, progress=None, broad_keep=None, on_parsed=None):
        result = self.source.load()[self.key]
        # Snapshot feeds the normal matcher, history and scoring, not a separate database.
        selected = [p for p in result.listings if keep(p.url) or (broad_keep and broad_keep(p.url))]
        return dataclasses.replace(result, listings=selected)

    def check(self):
        return "LOCAL_COLLECTOR", "Direktno očitavanje preko povezanog računara"


def collect(identity: str, max_pages=None) -> dict:
    from matching.matcher import Matcher
    from retailers.djaksport import DjakSportAdapter
    from retailers.planetasport import PlanetaSportAdapter
    # The same independent catalogue and broad running discovery as the cloud scanner.
    from common.config import load_config
    from catalog.loader import load_catalog
    from database.models import make_session_factory, CatalogModel
    from sqlalchemy import select
    from matching.matcher import CatalogEntry

    config = load_config()
    with tempfile.TemporaryDirectory() as directory:
        factory = make_session_factory(Path(directory) / "catalog.db")
        with factory() as session:
            load_catalog(session)
            matcher = Matcher([CatalogEntry(m.id, m.brand, m.model_name) for m in session.scalars(select(CatalogModel))])
        factory.kw["bind"].dispose()
    def work(cls):
        adapter = cls(delay_s=config["scan"]["default_delay_s"], max_retries=config["scan"]["max_retries"],
                      timeout_s=config["scan"]["request_timeout_s"], cache_hours=config["scan"]["sitemap_cache_hours"])
        def progress(key, index, total):
            print(f"{key}: {index}/{total}", flush=True)
        try:
            result = adapter.run(matcher.candidates_in_slug, max_pages=max_pages, broad_keep=lambda _: True, progress=progress)
        except Exception as exc:
            result = RetailerResult(adapter.key, message=f"Očitavanje nije uspelo: {type(exc).__name__}")
        if max_pages and result.candidates > max_pages and result.status == "VERIFIED":
            result.status = "PARTIAL"
            result.message = "Ograničena probna provera, nije potpun sken."
        print(f"{adapter.name}: {result.status}, stranica {result.pages_ok}, oglasa {len(result.listings)}", flush=True)
        return adapter.key, dataclasses.asdict(result)
    with ThreadPoolExecutor(max_workers=2) as pool:
        results = dict(pool.map(work, [DjakSportAdapter, PlanetaSportAdapter]))
    return {"version": VERSION, "repository": REPOSITORY, "run_id": run_id(identity), "created_at": now(), "results": results}


def verify_credentials() -> None:
    with tempfile.TemporaryDirectory() as folder:
        probe = download("stanje.enc", Path(folder))
        crypt("dec", probe, Path(folder) / "probe.tar.gz")


def worker(*, once=False) -> None:
    if not os.environ.get("PAGE_PASSWORD"):
        os.environ["PAGE_PASSWORD"] = getpass.getpass("Lozinka dashboarda (ostaje na ovom računaru): ")
    if len(os.environ["PAGE_PASSWORD"]) < 8:
        raise ValueError("Lozinka je prekratka")
    # Confirm both the password and Node before advertising availability.
    verify_credentials()
    completed = set()
    heartbeat_stop = threading.Event()
    heartbeat_ready = threading.Event()
    def heartbeat_loop():
        while not heartbeat_stop.is_set():
            try:
                with tempfile.TemporaryDirectory() as folder:
                    path = Path(folder) / HEARTBEAT
                    path.write_text(json.dumps({"version": VERSION, "repository": REPOSITORY, "updated_at": now()}), encoding="utf-8")
                    upload(path)
                    heartbeat_ready.set()
            except RuntimeError:
                print("Sakupljač trenutno nema vezu sa GitHubom.", flush=True)
            heartbeat_stop.wait(60)
    heartbeat_thread = threading.Thread(target=heartbeat_loop, daemon=True)
    heartbeat_thread.start()
    if not heartbeat_ready.wait(timeout=125):
        heartbeat_stop.set()
        raise RuntimeError("Nije moguće povezati sakupljač sa GitHubom.")
    print("Sakupljač je povezan. Pokreni sken na dashboardu; ovaj prozor ostavi otvoren.", flush=True)
    try:
        while True:
            try:
                remote = assets()
                candidates = [name for name in remote if re.fullmatch(r"direct-request-[1-9][0-9]{0,19}\.json", name)]
                candidates.sort(key=lambda name: int(name.removeprefix("direct-request-").removesuffix(".json")), reverse=True)
                for name in candidates:
                    identity = name.removeprefix("direct-request-").removesuffix(".json")
                    if identity in completed or asset_name("response", identity) in remote:
                        continue
                    with tempfile.TemporaryDirectory() as folder:
                        folder = Path(folder)
                        data = json.loads(download(name, folder).read_text(encoding="utf-8"))
                        try:
                            validate_request(data, identity)
                        except ValueError:
                            completed.add(identity)
                            continue
                        # Only a genuine owner-triggered or scheduled run of the known workflow is accepted.
                        run = json.loads(gh("api", f"repos/{REPOSITORY}/actions/runs/{identity}"))
                        if (run.get("status") != "in_progress" or run.get("path") != ".github/workflows/dnevni-sken.yml"
                                or run.get("event") not in {"schedule", "workflow_dispatch"}
                                or run.get("head_branch") != "main"
                                or (run.get("event") == "workflow_dispatch" and run.get("actor", {}).get("login") != "run-marko")):
                            completed.add(identity)
                            continue
                        result = collect(identity)
                        plain = folder / "results.json"
                        plain.write_text(json.dumps(result, ensure_ascii=False), encoding="utf-8")
                        encrypted = folder / asset_name("response", identity)
                        crypt("enc", plain, encrypted)
                        upload(encrypted)
                        completed.add(identity)
                        print("Rezultati poslati u isti sken. Dashboard će se osvežiti kada se završe i ostale prodavnice.", flush=True)
                        if once:
                            return
                    break
            except (RuntimeError, ValueError, OSError, KeyError) as exc:
                print(f"Sakupljač čeka: {exc}", flush=True)
            time.sleep(20)
    finally:
        heartbeat_stop.set()
        heartbeat_thread.join(timeout=5)
        # A stopped collector must not look online for another three minutes.
        try:
            gh("release", "delete-asset", RELEASE, HEARTBEAT, "--repo", REPOSITORY, "--yes")
        except RuntimeError:
            pass


def cleanup() -> None:
    identity = os.environ.get("DIRECT_COLLECTOR_RUN_ID")
    if not identity:
        return
    for kind in ("request", "response"):
        try:
            gh("release", "delete-asset", RELEASE, asset_name(kind, identity), "--repo", REPOSITORY, "--yes")
        except RuntimeError:
            pass


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=["request", "worker", "cleanup", "probe", "verify"])
    args = parser.parse_args()
    if args.mode == "verify":
        verify_credentials()
    elif args.mode == "request":
        request()
    elif args.mode == "cleanup":
        cleanup()
    elif args.mode == "probe":
        from retailers.djaksport import DjakSportAdapter
        from retailers.planetasport import PlanetaSportAdapter
        from common.http import FetchError
        targets = [
            (DjakSportAdapter, "https://www.djaksport.com/adidas-patike-adizero-evo-sl-m-za-muskarce-jh6206"),
            (PlanetaSportAdapter, "https://planetasport.rs/adidas-patike-supernova-ease-2-m-jq4335.html"),
        ]
        failed = False
        for cls, url in targets:
            adapter = cls(max_retries=0)
            try:
                response = adapter.client.get(url)
                item = adapter.parse_page(response.text, url)[0]
                available = [size.label for size in item.sizes if size.available is True]
                print(f"{adapter.name}: pročitan proizvod, cena {item.current_price} RSD; dostupni brojevi: {', '.join(available) or 'nisu potvrđeni'}", flush=True)
            except (FetchError, ValueError, IndexError, TypeError) as exc:
                print(f"{adapter.name}: provera nije uspela ({type(exc).__name__}).", flush=True)
                failed = True
        if failed:
            raise SystemExit(1)
    else:
        worker()


if __name__ == "__main__":
    main()
